# Python math Module
import math
# constants
print(math.e) 
print(math.pi)

# methods
print(math.fabs(-5))
print(math.fabs(8)) 

square_root = math.sqrt(25)
print(square_root)

print(math.pow(2, 5))
print(math.pow(11, 3))

# n! = 1 * 2 * 3 * 4 * ... * n
print(math.factorial(5))

# up rounding
print(math.ceil(4.3))

# Down rounding
print(math.floor(4.7))

# sin/cos/tg/ctg
print(math.sin(math.radians(90))) 
print(math.cos(math.radians(30)))
print(math.tan(math.radians(90))) 

